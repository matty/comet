#[derive(Clone, Debug)]
pub struct SanitizationReport {
    pub events_path: PathBuf,
    pub manifest_path: PathBuf,
    pub events_bytes: Vec<u8>,
    pub manifest_bytes: Vec<u8>,
    /// Every published path whose last segment is a key that carried a path
    /// delimiter and had to be escaped, sorted. Informational, never a
    /// rejection: the escape makes such a key harmless
    /// ([`surface::escape_path_segment`]), but a provider that starts naming
    /// its fields `x.ai/…` is worth one human glance, and refusing the
    /// capture used to be what forced that glance. This is the replacement —
    /// it reports rather than blocks, and it is also where the exact spelling
    /// an allowlist line has to match can be copied from.
    pub escaped_paths: Vec<String>,
    /// Every dotted path the allowlist withheld a value for, sorted by path.
    /// The allowlist's fail-closed default is only useful if what it
    /// withholds is visible: this is that visibility, without ever
    /// reproducing what was withheld. See `NovelPath` for what each entry
    /// carries and, just as importantly, what it deliberately does not.
    pub novel_paths: Vec<NovelPath>,
}

/// One path the allowlist withheld a value for, described without
/// reproducing the value: just enough shape to triage whether the path
/// looks safe to add to the allowlist, never enough to read what a
/// withheld field actually said.
///
/// Deliberately excludes the `mcp__` exception (`is_mcp_tool_identity`):
/// that path *is* on the allowlist and its withholding is an already-
/// reviewed, documented rule, not something nobody has considered. Naming
/// it here would file a settled decision back under "novel" and dilute the
/// list this exists to keep short and actionable. See the doc comment on
/// `is_mcp_tool_identity` for the reviewed reasoning behind that exception.
///
/// `path` can name a **field**, and field names are published deliberately —
/// each version's capability sheet (`docs/providers/<provider>-<version>.md`,
/// generated by `crates/harness/src/capture/sheet.rs`) is a snapshot of
/// exactly those names. What it can never name is a **map key**: a key under
/// one of
/// `surface::MAP_PATHS` is data, so an unreviewed one is replaced before the
/// path is built, and the entry it produces reads `.modelUsage.{}` with the
/// key counted as a withheld value. `.modelUsage.claude-haiku-4-5-20251001`
/// still appears verbatim, because those two literal lines are on
/// `allowlist/claude.txt` and a listed path is a decision to publish.
///
/// An earlier version of this comment argued no key needed redacting at all,
/// on the grounds that `validate_key` fail-closed-scans every one. That scan
/// is a *blocklist* — redaction roots, absolute paths, secret shapes — which
/// is the thing this whole module replaced in value position, and it has
/// nothing to say about a key that names a machine, an account or a
/// connector. Keys are now default-deny wherever they are data.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NovelPath {
    pub path: String,
    pub distinct_values: usize,
    /// The JSON type and, for strings, a length or length range —
    /// `"string len 8-42"`, `"number"`, `"bool"` — computed from the
    /// withheld values but never equal to any of them.
    pub shape: String,
}

#[derive(Debug, thiserror::Error)]
pub enum SanitizationError {
    #[error("raw capture could not be read")]
    ReadRaw {
        #[source]
        source: std::io::Error,
    },
    #[error("raw capture is not valid capture JSON")]
    InvalidRaw {
        #[source]
        source: serde_json::Error,
    },
    #[error("incomplete capture evidence cannot be sanitized or promoted")]
    IncompleteCapture,
    #[error("staging output must be below .comet-provider-captures/staging")]
    UnsafeOutputDirectory,
    #[error("capture contains an unrecognized absolute path at {location}")]
    UnrecognizedAbsolutePath { location: String },
    #[error("capture contains a secret-like field at {location}")]
    SecretLikeField { location: String },
    #[error("capture contains a secret-like value at {location}")]
    SecretLikeValue { location: String },
    #[error("capture contains a sensitive object key at {location}")]
    SensitiveObjectKey { location: String },
    #[error("capture contains a value shaped like a generated placeholder at {location}")]
    PlaceholderShapedValue { location: String },
    #[error("capture channel contains unparseable structured JSON at sequence {sequence}")]
    UnparseableStructuredPayload { sequence: u64 },
    #[error("Claude capture command has invalid resume arguments at {location}")]
    InvalidClaudeResumeCommand { location: String },
    #[error("sanitized capture could not be written")]
    WriteOutput {
        #[source]
        source: std::io::Error,
    },
    #[error("sanitized staging destination is busy; retry after the other publisher finishes")]
    PublicationBusy {
        #[source]
        source: std::io::Error,
    },
    #[error("sanitized staging destination already contains different evidence")]
    PublicationConflict {
        #[source]
        source: std::io::Error,
    },
    #[error("sanitized capture could not be encoded")]
    EncodeOutput {
        #[source]
        source: serde_json::Error,
    },
}

/// Per-capture redaction state: which values have already been assigned a
/// placeholder.
///
/// Numbering is keyed on the original value, not on a counter, so equal
/// values collide into the same placeholder deliberately — a join that held
/// on the wire still holds in the archive. `named` groups are the six
/// identifier kinds from `allowlist::named_kind` (plus the internal `PROSE`
/// group for non-JSON stderr payloads); `generic` is the numbered fallback
/// (`<V1>`, `<V2>`, …) for every other unlisted scalar. Both are `Vec`, not
/// `HashMap`, because encounter order is what makes a run byte-deterministic
/// — the publication tests assert on that determinism directly.
///
/// No longer carries a `counts` accounting map — `placeholders` and
/// `redaction_counts` were dropped from the written manifest at the stage-6
/// promotion, since nobody read the per-category counts.
#[derive(Default)]
struct Redactor {
    paths: Vec<PathRedaction>,
    named: BTreeMap<&'static str, Vec<(Value, String)>>,
    generic: Vec<(Value, String)>,
    /// Distinct raw values seen at each path the allowlist withheld,
    /// keyed by dotted path (`BTreeMap` for path-sorted, deterministic
    /// iteration). Never leaves this struct as raw values -- `novel_paths`
    /// reduces each entry to a count and a shape before it becomes a
    /// `NovelPath`. Excludes the `mcp__` exception deliberately; see
    /// `NovelPath`'s doc comment.
    novel: BTreeMap<String, Vec<Value>>,
    /// Every path whose last segment came from a key that had to be
    /// escaped, and that survived as a published field name. Only
    /// survivors: an escaped key that was *replaced* is data (a model id
    /// keying a declared map), and spelling it here would republish
    /// exactly what the replacement withheld -- `novel` already counts
    /// that one at its `.{}` position.
    escaped: BTreeSet<String>,
}

#[derive(Clone)]
struct PathRedaction {
    values: Vec<String>,
    placeholder: &'static str,
}

/// Convert one raw capture into reviewable staging artifacts.
///
/// All transformation and validation happens in memory. A rejected capture never creates its
/// output directory, and errors identify only the value's structural location.
pub fn sanitize_dir(
    raw_dir: &Path,
    output_dir: &Path,
) -> Result<SanitizationReport, SanitizationError> {
    if !is_staging_output(output_dir) {
        return Err(SanitizationError::UnsafeOutputDirectory);
    }

    let capture_path = raw_dir.join("capture.json");
    let partial_path = raw_dir.join("partial-capture.json");
    if partial_path.exists() {
        let bytes =
            std::fs::read(partial_path).map_err(|source| SanitizationError::ReadRaw { source })?;
        let _: PartialRawCapture = serde_json::from_slice(&bytes)
            .map_err(|source| SanitizationError::InvalidRaw { source })?;
        return Err(SanitizationError::IncompleteCapture);
    }
    let bytes =
        std::fs::read(capture_path).map_err(|source| SanitizationError::ReadRaw { source })?;
    let capture: RawCapture = serde_json::from_slice(&bytes)
        .map_err(|source| SanitizationError::InvalidRaw { source })?;
    let mut redactor = Redactor::new(&capture);

    let mut payloads = Vec::with_capacity(capture.events.len());
    for event in &capture.events {
        match serde_json::from_str::<Value>(&event.payload) {
            Ok(payload) => payloads.push(Payload::Json(payload)),
            Err(_) if event.channel == Channel::Stderr => {
                payloads.push(Payload::Text(event.payload.clone()))
            }
            Err(_) => {
                return Err(SanitizationError::UnparseableStructuredPayload {
                    sequence: event.sequence,
                });
            }
        }
    }

    // Events are sanitized before `command`, deliberately: the Claude resume
    // argv below needs the session id's placeholder already assigned, and a
    // session id normally first appears inside an event payload, not in
    // `command` itself.
    let mut events_bytes = Vec::new();
    for (event, payload) in capture.events.iter().zip(&mut payloads) {
        let payload = match payload {
            Payload::Json(value) => {
                redactor.sanitize_value_tree(value, capture.provider, "", "", "event.payload")?;
                serde_json::to_string(value)
                    .map_err(|source| SanitizationError::EncodeOutput { source })?
            }
            Payload::Text(text) => {
                let placeholder = redactor.placeholder_for_prose(text);
                *text = placeholder.clone();
                placeholder
            }
        };
        let line = SanitizedEvent {
            sequence: event.sequence,
            channel: event.channel,
            payload,
        };
        serde_json::to_writer(&mut events_bytes, &line)
            .map_err(|source| SanitizationError::EncodeOutput { source })?;
        events_bytes.push(b'\n');
    }

    let mut command = serde_json::to_value(&capture.command)
        .map_err(|source| SanitizationError::EncodeOutput { source })?;
    if capture.provider == Provider::Claude {
        redactor.sanitize_claude_resume_argv(&mut command, &capture.scenario)?;
    }
    redactor.sanitize_nonsemantic_value(&mut command, "command")?;

    let mut cli_version = capture.cli_version.clone();
    redactor.sanitize_paths_and_validate(&mut cli_version, "cli_version")?;
    let mut scenario = capture.scenario.clone();
    redactor.sanitize_paths_and_validate(&mut scenario, "scenario")?;
    let mut purpose = capture.purpose.clone();
    redactor.sanitize_paths_and_validate(&mut purpose, "purpose")?;
    let mut platform = serde_json::to_value(&capture.platform)
        .map_err(|source| SanitizationError::EncodeOutput { source })?;
    redactor.sanitize_nonsemantic_value(&mut platform, "platform")?;
    // The manifest is provenance only, stage-6 promotion onward: `source`,
    // `normalized_cli_version`, `channels`, `placeholders` and
    // `redaction_counts` were all dropped -- nothing under `crates/` read any
    // of them.
    let novel_paths = redactor.novel_paths();
    let escaped_paths = redactor.escaped_paths();
    let manifest = json!({
        "schema_version": 1,
        "provider": capture.provider,
        "cli_version": cli_version,
        "captured_at_unix_ms": capture.captured_at_unix_ms,
        "scenario": scenario,
        "purpose": purpose,
        "platform": platform,
        "command": command,
        "exit_code": capture.exit_code,
    });
    let mut manifest_bytes = serde_json::to_vec_pretty(&manifest)
        .map_err(|source| SanitizationError::EncodeOutput { source })?;
    manifest_bytes.push(b'\n');

    let events_path = output_dir.join("events.jsonl");
    let manifest_path = output_dir.join("manifest.json");
    publish_staging_pair_with(output_dir, &events_bytes, &manifest_bytes, |_| Ok(())).map_err(
        |source| match source.kind() {
            std::io::ErrorKind::WouldBlock => SanitizationError::PublicationBusy { source },
            std::io::ErrorKind::AlreadyExists => SanitizationError::PublicationConflict { source },
            _ => SanitizationError::WriteOutput { source },
        },
    )?;

    Ok(SanitizationReport {
        events_path,
        manifest_path,
        events_bytes,
        manifest_bytes,
        novel_paths,
        escaped_paths,
    })
}

fn publish_staging_pair_with<F>(
    output_dir: &Path,
    events: &[u8],
    manifest: &[u8],
    after_events: F,
) -> std::io::Result<()>
where
    F: FnOnce(&Path) -> std::io::Result<()>,
{
    publish_staging_pair_with_commit(output_dir, events, manifest, after_events, |from, to| {
        std::fs::rename(from, to)
    })
}

fn publish_staging_pair_with_commit<F, C>(
    output_dir: &Path,
    events: &[u8],
    manifest: &[u8],
    after_events: F,
    commit: C,
) -> std::io::Result<()>
where
    F: FnOnce(&Path) -> std::io::Result<()>,
    C: FnOnce(&Path, &Path) -> std::io::Result<()>,
{
    let parent = output_dir.parent().ok_or_else(|| {
        std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "staging destination has no parent",
        )
    })?;
    std::fs::create_dir_all(parent)?;
    let output_name = output_dir
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("capture");
    let publication_lock = PublicationLock::acquire(parent, output_name)?;
    let result = (|| {
        let temporary_prefix = format!(".{output_name}.sanitize-");
        let temporary = parent.join(format!("{temporary_prefix}{}", uuid::Uuid::new_v4()));
        std::fs::create_dir(&temporary)?;

        let prepared = (|| {
            write_synced(&temporary.join("events.jsonl"), events)?;
            after_events(&temporary)?;
            write_synced(&temporary.join("manifest.json"), manifest)?;
            Ok(())
        })();
        if let Err(error) = prepared {
            let _ = remove_verified_generated_dir(&temporary, parent, &temporary_prefix);
            return Err(error);
        }

        if output_dir.exists() {
            let identical = match destination_is_exact_pair(output_dir, events, manifest) {
                Ok(identical) => identical,
                Err(error) => {
                    let _ = remove_verified_generated_dir(&temporary, parent, &temporary_prefix);
                    return Err(error);
                }
            };
            remove_verified_generated_dir(&temporary, parent, &temporary_prefix)?;
            if identical {
                return Ok(());
            }
            return Err(std::io::Error::new(
                std::io::ErrorKind::AlreadyExists,
                "sanitized staging destination already contains different evidence",
            ));
        }

        if let Err(error) = commit(&temporary, output_dir) {
            let _ = remove_verified_generated_dir(&temporary, parent, &temporary_prefix);
            return Err(error);
        }
        Ok(())
    })();
    match publication_lock.release() {
        Ok(()) => result,
        Err(error) => Err(error),
    }
}

fn destination_is_exact_pair(
    output_dir: &Path,
    expected_events: &[u8],
    expected_manifest: &[u8],
) -> std::io::Result<bool> {
    let directory_metadata = std::fs::symlink_metadata(output_dir)?;
    if !directory_metadata.file_type().is_dir()
        || directory_metadata.file_type().is_symlink()
        || has_windows_reparse_point(&directory_metadata)
    {
        return Ok(false);
    }

    let mut events_match = false;
    let mut manifest_match = false;
    let mut entry_count = 0;
    for entry in std::fs::read_dir(output_dir)? {
        let entry = entry?;
        entry_count += 1;
        let metadata = std::fs::symlink_metadata(entry.path())?;
        if !metadata.file_type().is_file()
            || metadata.file_type().is_symlink()
            || has_windows_reparse_point(&metadata)
        {
            return Ok(false);
        }
        if entry.file_name() == "events.jsonl" {
            events_match = std::fs::read(entry.path())? == expected_events;
        } else if entry.file_name() == "manifest.json" {
            manifest_match = std::fs::read(entry.path())? == expected_manifest;
        } else {
            return Ok(false);
        }
    }
    Ok(entry_count == 2 && events_match && manifest_match)
}

struct PublicationLock {
    _file: std::fs::File,
    path: PathBuf,
    parent: PathBuf,
    name: String,
    owner: String,
}

impl PublicationLock {
    fn acquire(parent: &Path, output_name: &str) -> std::io::Result<Self> {
        let parent = std::fs::canonicalize(parent)?;
        let name = format!(".{output_name}.publish.lock");
        let path = parent.join(&name);
        if path.parent() != Some(parent.as_path()) || path.file_name() != Some(name.as_ref()) {
            return Err(std::io::Error::new(
                std::io::ErrorKind::PermissionDenied,
                "refusing to create an unverified publication lock",
            ));
        }
        let mut file = match std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
        {
            Ok(file) => file,
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {
                return Err(std::io::Error::new(
                    std::io::ErrorKind::WouldBlock,
                    "sanitized staging destination is busy",
                ));
            }
            Err(error) => return Err(error),
        };
        let owner = uuid::Uuid::new_v4().to_string();
        {
            use std::io::Write as _;
            file.write_all(owner.as_bytes())?;
            file.sync_all()?;
        }
        Ok(Self {
            _file: file,
            path,
            parent,
            name,
            owner,
        })
    }

    fn release(self) -> std::io::Result<()> {
        remove_verified_generated_file(&self.path, &self.parent, &self.name, self.owner.as_bytes())
    }
}

fn write_synced(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write as _;

    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?;
    file.write_all(bytes)?;
    file.sync_all()
}

fn remove_verified_generated_dir(
    generated: &Path,
    parent: &Path,
    expected_prefix: &str,
) -> std::io::Result<()> {
    let resolved_parent = std::fs::canonicalize(parent)?;
    let resolved_generated = std::fs::canonicalize(generated)?;
    let valid_name = resolved_generated
        .file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| name.starts_with(expected_prefix));
    if resolved_generated.parent() != Some(resolved_parent.as_path()) || !valid_name {
        return Err(std::io::Error::new(
            std::io::ErrorKind::PermissionDenied,
            "refusing to clean an unverified staging sibling",
        ));
    }
    std::fs::remove_dir_all(resolved_generated)
}

fn remove_verified_generated_file(
    generated: &Path,
    parent: &Path,
    expected_name: &str,
    expected_contents: &[u8],
) -> std::io::Result<()> {
    let resolved_parent = std::fs::canonicalize(parent)?;
    let resolved_generated = std::fs::canonicalize(generated)?;
    let metadata = std::fs::symlink_metadata(generated)?;
    let valid_name = resolved_generated.file_name() == Some(expected_name.as_ref());
    if resolved_generated.parent() != Some(resolved_parent.as_path())
        || !valid_name
        || !metadata.file_type().is_file()
        || metadata.file_type().is_symlink()
        || has_windows_reparse_point(&metadata)
        || std::fs::read(generated)? != expected_contents
    {
        return Err(std::io::Error::new(
            std::io::ErrorKind::PermissionDenied,
            "refusing to clean an unverified publication lock",
        ));
    }
    std::fs::remove_file(resolved_generated)
}

#[derive(Serialize)]
struct SanitizedEvent {
    sequence: u64,
    channel: Channel,
    payload: String,
}

enum Payload {
    Json(Value),
    Text(String),
}

impl Redactor {
    fn new(capture: &RawCapture) -> Self {
        let mut redactor = Self::default();
        redactor.add_path(capture.redaction_roots.cwd.as_deref(), "<CWD>");
        redactor.add_path(capture.redaction_roots.repo.as_deref(), "<REPO>");
        redactor.add_path(capture.redaction_roots.home.as_deref(), "<HOME>");
        redactor.add_path(capture.redaction_roots.temp.as_deref(), "<TEMP>");
        redactor.add_path(
            capture.redaction_roots.codex_home.as_deref(),
            "<CODEX_HOME>",
        );
        redactor.add_path(
            capture.redaction_roots.claude_config_dir.as_deref(),
            "<CLAUDE_CONFIG_DIR>",
        );
        redactor.add_path(
            capture.redaction_roots.approval_target.as_deref(),
            "<APPROVAL_TARGET>",
        );
        redactor.add_path(
            capture.redaction_roots.trusted_powershell.as_deref(),
            "<TRUSTED_POWERSHELL>",
        );
        redactor.add_uncovered_program_root(&capture.command.program);
        redactor
    }

    /// The directory the captured program itself was launched from, as a root
    /// of last resort — added only when none of the eight above already
    /// covers it.
    ///
    /// Without this, a capture whose program lives outside every declared
    /// category cannot be sanitized at all: `sanitize_paths_and_validate`
    /// refuses a leftover absolute path rather than publishing it, and
    /// `command.program` is in the manifest, so the run dies at
    /// `command.object[5]` with a message that names a JSON position and not
    /// a reason. That is not hypothetical — the ACP adapter rows spawn
    /// `node`, and a system-wide install resolves to
    /// `C:\Program Files\nodejs\node.exe`, under none of `RedactionRoots`'
    /// categories. The 2026-08-28 promotion worked around it by re-recording
    /// with `--executable` pointed at an interpreter that happened to live
    /// under `<HOME>`; an operator with only an ordinary install has nothing
    /// to reach for (D102's third gap).
    ///
    /// **Only when uncovered**, because `add_path` ranks roots by string
    /// length: `C:\Users\me\.grok\bin` is longer than `C:\Users\me`, so an
    /// unconditional program root would outrank `<HOME>` and silently
    /// respell every capture that sanitizes correctly today —
    /// `<HOME>\.grok\bin\grok.exe` becoming `<PROGRAM_DIR>\grok.exe`, losing
    /// the directory the manifest currently shows. Derived here from
    /// `command.program` rather than recorded as a ninth `RedactionRoots`
    /// field on purpose: the program is already in every capture, including
    /// the ones recorded before this existed, so the fix reaches them too.
    fn add_uncovered_program_root(&mut self, program: &str) {
        let Some(directory) = Path::new(program).parent() else {
            return;
        };
        let directory = directory.to_string_lossy();
        // The same predicate that would later reject the leftover, not a
        // separate notion of "absolute": this adds a root exactly when its
        // absence is what fails the capture, and stays silent otherwise (a
        // bare `claude` has an empty parent, and a relative one has nothing
        // `sanitize_paths_and_validate` would object to).
        if !contains_absolute_path(&directory) {
            return;
        }
        let covered = self.paths.iter().any(|redaction| {
            redaction
                .values
                .iter()
                .any(|known| directory.starts_with(known.as_str()))
        });
        if covered {
            return;
        }
        self.add_path(Some(directory.as_ref()), "<PROGRAM_DIR>");
    }

    fn add_path(&mut self, value: Option<&str>, placeholder: &'static str) {
        let Some(value) = value.filter(|value| !value.is_empty()) else {
            return;
        };
        if self
            .paths
            .iter()
            .any(|redaction| redaction.values.iter().any(|known| known == value))
        {
            return;
        }
        let mut values = vec![value.to_owned()];
        let slash = value.replace('\\', "/");
        let backslash = value.replace('/', "\\");
        for variant in [slash, backslash] {
            if !values.contains(&variant) {
                values.push(variant);
            }
        }
        for variant in values.clone() {
            if is_drive_absolute(&variant) {
                values.push(format!(r"\\?\{variant}"));
                values.push(format!("//?/{variant}"));
            }
        }
        values.sort_by_key(|value| std::cmp::Reverse(value.len()));
        self.paths.push(PathRedaction {
            values,
            placeholder,
        });
        self.paths
            .sort_by_key(|path| std::cmp::Reverse(path.values.first().map_or(0, String::len)));
    }

    /// The allowlist walker. For each scalar (`String`/`Number`) at dotted
    /// path `path`: if its field name looks credential-shaped, reject the
    /// whole capture regardless of allow status — `is_secret_field` is a
    /// tripwire independent of the allowlist, because a name like
    /// `apiKey`/`authorization` showing up anywhere is itself the alarm.
    /// Otherwise, if `path` is on the provider's allowlist, keep the value
    /// verbatim and run the fail-closed scan over it — an allowlisted path
    /// is a decision about the *field*, not a licence for whatever a
    /// provider happens to put in it. If it is not allowed, replace it with
    /// a placeholder. `Bool`/`Null` are never redacted: they carry no
    /// free-form data.
    ///
    /// `Array`/`Object` recurse; an array element's path grows `[]` (never
    /// an index, so every element of an array shares one allowlist
    /// decision) and its `key` stays the containing field's key, so
    /// `is_secret_field`/`named_kind` still see a meaningful field name for
    /// each scalar inside e.g. `"tags": ["sk-ant-…"]`.
    fn sanitize_value_tree(
        &mut self,
        value: &mut Value,
        provider: Provider,
        path: &str,
        key: &str,
        location: &str,
    ) -> Result<(), SanitizationError> {
        match value {
            Value::Array(items) => {
                let child_path = format!("{path}[]");
                for (index, item) in items.iter_mut().enumerate() {
                    self.sanitize_value_tree(
                        item,
                        provider,
                        &child_path,
                        key,
                        &format!("{location}[{index}]"),
                    )?;
                }
                Ok(())
            }
            Value::Object(object) => {
                // Keys under a declared map path are data, not field names, so
                // they redact by the same default-deny rule as a value. The
                // object is rebuilt rather than mutated in place because a
                // redacted key is a *rename*, and remove-then-insert on the
                // map being iterated is order-dependent under serde_json's
                // `preserve_order` feature. Rebuilding in iteration order is
                // correct whichever backend is compiled in.
                let is_map = surface::MAP_PATHS.contains(&path);
                let mut rebuilt = serde_json::Map::with_capacity(object.len());
                for (index, (child_key, mut child)) in
                    std::mem::take(object).into_iter().enumerate()
                {
                    let child_location = format!("{location}.object[{index}]");
                    self.validate_key(&child_key, &child_location)?;
                    let escaped_key = surface::escape_path_segment(&child_key);
                    let key_needed_escaping = matches!(escaped_key, std::borrow::Cow::Owned(_));
                    let candidate_path = format!("{path}.{escaped_key}");
                    let key_survives = !is_map || allows_prefix(provider, &candidate_path);
                    let (child_key, child_path) = if key_survives {
                        if key_needed_escaping {
                            self.escaped.insert(candidate_path.clone());
                        }
                        (child_key, candidate_path)
                    } else {
                        // Reported at the map-key *position* (`surface.rs`'s
                        // own `{}` notation), never at the key itself: a
                        // report that named the path verbatim would republish
                        // exactly the identifier this branch just withheld.
                        // The key rides through as the withheld *value*, which
                        // `novel_paths` reduces to a count and a shape.
                        self.record_novel(
                            &format!("{path}.{{}}"),
                            &Value::String(child_key.clone()),
                        );
                        // Generic `<Vn>`, not a named group: a map key is not
                        // one of the six kinds anything reads, and the same
                        // identifier appearing elsewhere as a value still
                        // shares its placeholder, so joins survive.
                        let placeholder = self.resolve(&Value::String(child_key), None);
                        let child_path = format!("{path}.{placeholder}");
                        (placeholder, child_path)
                    };
                    self.sanitize_value_tree(
                        &mut child,
                        provider,
                        &child_path,
                        &child_key,
                        &child_location,
                    )?;
                    rebuilt.insert(child_key, child);
                }
                *object = rebuilt;
                Ok(())
            }
            Value::String(_) | Value::Number(_) => {
                self.sanitize_scalar(value, provider, path, key, location)
            }
            _ => Ok(()),
        }
    }

    fn sanitize_scalar(
        &mut self,
        value: &mut Value,
        provider: Provider,
        path: &str,
        key: &str,
        location: &str,
    ) -> Result<(), SanitizationError> {
        if is_secret_field(key, value) {
            return Err(SanitizationError::SecretLikeField {
                location: location.to_owned(),
            });
        }
        let path_allowed = allows(provider, path);
        if path_allowed && !is_mcp_tool_identity(value) {
            if let Value::String(text) = value {
                if is_generated_placeholder_shape(text) {
                    return Err(SanitizationError::PlaceholderShapedValue {
                        location: location.to_owned(),
                    });
                }
                self.sanitize_paths_and_validate(text, location)?;
            }
            return Ok(());
        }
        if !path_allowed {
            self.record_novel(path, value);
        }
        let placeholder = self.placeholder_for(key, value);
        *value = Value::String(placeholder);
        Ok(())
    }

    /// Records one occurrence of a withheld value at `path`, for the novel-
    /// path report. Only called for paths that are not on the allowlist at
    /// all -- an `mcp__` value on an allowed path never reaches here (see
    /// `sanitize_scalar`). Deduplicates by value equality, so a path seen in
    /// many frames with the same literal value counts once, and the same
    /// path with genuinely different values counts each of them -- that is
    /// what `distinct_values` means.
    fn record_novel(&mut self, path: &str, value: &Value) {
        let seen = self.novel.entry(path.to_owned()).or_default();
        if !seen.iter().any(|known| known == value) {
            seen.push(value.clone());
        }
    }

    /// Reduces the accumulated withheld values into the report shape: one
    /// `NovelPath` per path, sorted by path (inherited from `BTreeMap`'s
    /// iteration order), holding a count and a shape but never a value.
    /// The escaped, published paths, sorted (`BTreeSet` iteration order).
    fn escaped_paths(&self) -> Vec<String> {
        self.escaped.iter().cloned().collect()
    }

    fn novel_paths(&self) -> Vec<NovelPath> {
        self.novel
            .iter()
            .map(|(path, values)| NovelPath {
                path: path.clone(),
                distinct_values: values.len(),
                shape: describe_shape(values),
            })
            .collect()
    }

    /// The placeholder for `value` under `key`'s named group —
    /// `named_kind(key)` if it is one of the six identifier leaves
    /// (`<SESSION_1>`, …), otherwise the generic `<V1>` fallback.
    fn placeholder_for(&mut self, key: &str, value: &Value) -> String {
        self.resolve(value, named_kind(key))
    }

    /// The single stderr-prose placeholder group: non-JSON payloads (always
    /// `Channel::Stderr`; anything else fails the capture earlier) collapse
    /// to `<PROSE_n>`, with equal text sharing a number like every other
    /// group.
    fn placeholder_for_prose(&mut self, text: &str) -> String {
        self.resolve(&Value::String(text.to_owned()), Some("PROSE"))
    }

    /// Identity comes from the value, not from a kind: `resolve` first
    /// searches *every* group — named and generic — for `value`, regardless
    /// of `fallback_group`, so a value already redacted under one field's
    /// name (say `sessionId`) reuses that exact placeholder when the same
    /// literal value shows up again under an unrelated field (say `echo`).
    /// Only a genuinely new value gets a fresh placeholder, assigned into
    /// `fallback_group` (or the generic `<V n>` fallback when `None`) using
    /// that group's own next number.
    ///
    /// Encounter order, not a `HashMap`, is what makes this deterministic:
    /// both `named` and `generic` are `Vec`s scanned linearly, so the same
    /// capture always numbers the same way — the property the publication
    /// tests assert on as byte determinism.
    fn resolve(&mut self, value: &Value, fallback_group: Option<&'static str>) -> String {
        if let Some(placeholder) = self.existing_placeholder(value) {
            return placeholder;
        }
        match fallback_group {
            Some(name) => {
                let group = self.named.entry(name).or_default();
                let placeholder = format!("<{name}_{}>", group.len() + 1);
                group.push((value.clone(), placeholder.clone()));
                placeholder
            }
            None => {
                let placeholder = format!("<V{}>", self.generic.len() + 1);
                self.generic.push((value.clone(), placeholder.clone()));
                placeholder
            }
        }
    }

    /// The placeholder `value` was already assigned, in whichever group it
    /// landed in — or `None` if this sanitizer has never seen the value.
    /// Never allocates a new placeholder, which is what makes it usable as a
    /// *lookup* by callers that must not invent one.
    fn existing_placeholder(&mut self, value: &Value) -> Option<String> {
        for group in self.named.values() {
            if let Some((_, placeholder)) = group.iter().find(|(known, _)| known == value) {
                return Some(placeholder.clone());
            }
        }
        self.generic
            .iter()
            .find(|(known, _)| known == value)
            .map(|(_, placeholder)| placeholder.clone())
    }

    fn sanitize_nonsemantic_value(
        &mut self,
        value: &mut Value,
        location: &str,
    ) -> Result<(), SanitizationError> {
        match value {
            Value::Array(values) => {
                for (index, value) in values.iter_mut().enumerate() {
                    self.sanitize_nonsemantic_value(value, &format!("{location}[{index}]"))?;
                }
            }
            Value::Object(object) => {
                for (index, (key, value)) in object.iter_mut().enumerate() {
                    let child_location = format!("{location}.object[{index}]");
                    self.validate_key(key, &child_location)?;
                    if is_secret_field(key, value) {
                        return Err(SanitizationError::SecretLikeField {
                            location: child_location,
                        });
                    }
                    self.sanitize_nonsemantic_value(value, &child_location)?;
                }
            }
            Value::String(text) => self.sanitize_paths_and_validate(text, location)?,
            _ => {}
        }
        Ok(())
    }

    /// A key is rejected if it carries something the *value* scan would have
    /// redacted — a real absolute path, a secret shape — because a key is
    /// published verbatim and cannot be placeholdered in place.
    ///
    /// It is **not** rejected for carrying a path delimiter any more. That
    /// check existed to stop a key from impersonating nesting, and its own
    /// comment asked for a path-encoding decision on the day a real provider
    /// emitted a dotted key. Grok does, ten ways
    /// ([`surface::escape_path_segment`] has the evidence), so the decision was
    /// made there: every key is escaped as it is joined into a path, which
    /// removes the ambiguity structurally rather than by refusing the capture.
    /// Nothing else about this function's fail-closed posture changed.
    fn validate_key(&mut self, key: &str, location: &str) -> Result<(), SanitizationError> {
        let mut sanitized = key.to_owned();
        self.sanitize_paths_and_validate(&mut sanitized, location)?;
        if sanitized != key {
            return Err(SanitizationError::SensitiveObjectKey {
                location: location.to_owned(),
            });
        }
        Ok(())
    }

    /// Whether `scenario`'s argv may legitimately carry `--resume=<id>`.
    ///
    /// The rule this gates is fail-closed on purpose: a `--resume` in a
    /// capture that had no business resuming is evidence the command was not
    /// what the scenario says, and that must stop promotion rather than be
    /// sanitized away. Reads `Requirements::needs_resume_id` off the one
    /// scenario table (**D60**: `record::scenarios::SCENARIOS`) rather than
    /// repeating the permitted set as a literal here — a literal here was
    /// exactly the fourth unsynchronized copy D60 closed the other three of;
    /// every new resume-bearing scenario was rejected until someone found
    /// this function (`checklist-resume` was, and the error
    /// `Claude capture command has invalid resume arguments at command.args`
    /// names the argv rather than the missing registration).
    fn claude_scenario_allows_resume(scenario: &str) -> bool {
        super::record::scenario("claude", scenario)
            .is_some_and(|spec| spec.requirements.needs_resume_id)
    }

    fn sanitize_claude_resume_argv(
        &mut self,
        command: &mut Value,
        scenario: &str,
    ) -> Result<(), SanitizationError> {
        let Some(args) = command.get_mut("args").and_then(Value::as_array_mut) else {
            return Err(SanitizationError::InvalidClaudeResumeCommand {
                location: "command.args".to_owned(),
            });
        };
        let resume_like: Vec<usize> = args
            .iter()
            .enumerate()
            .filter_map(|(index, arg)| {
                arg.as_str()
                    .is_some_and(|arg| arg.starts_with("--resume"))
                    .then_some(index)
            })
            .collect();
        if !Self::claude_scenario_allows_resume(scenario) {
            if resume_like.is_empty() {
                return Ok(());
            }
            return Err(SanitizationError::InvalidClaudeResumeCommand {
                location: "command.args".to_owned(),
            });
        }

        let Some(&index) = resume_like
            .as_slice()
            .first()
            .filter(|_| resume_like.len() == 1)
        else {
            return Err(SanitizationError::InvalidClaudeResumeCommand {
                location: "command.args".to_owned(),
            });
        };
        let Some(raw_session_id) = args[index]
            .as_str()
            .and_then(|arg| arg.strip_prefix("--resume="))
            .filter(|session_id| !session_id.is_empty())
            .map(str::to_owned)
        else {
            return Err(SanitizationError::InvalidClaudeResumeCommand {
                location: "command.args".to_owned(),
            });
        };
        // Looked up by the value in argv, not by reading whatever single
        // entry the SESSION group happens to hold. The requirement is
        // unchanged — this id must be one the events already redacted, so a
        // capture whose argv disagrees with its own frames still stops — but
        // reading the group directly made two ordinary captures fail with a
        // message about invalid resume arguments:
        //
        //   * the id first appearing under a key `named_kind` does not name
        //     (it takes the generic `<Vn>` group, and nothing ever populates
        //     SESSION), and
        //   * any capture holding a *second* distinct session id, which a
        //     resume that spawns a subagent produces — the old code required
        //     the group to be exactly one element long.
        //
        // Neither is reachable in the committed corpus, which is why both
        // survived to be found by review rather than by a red test.
        let Some(placeholder) = self.existing_placeholder(&Value::String(raw_session_id)) else {
            return Err(SanitizationError::InvalidClaudeResumeCommand {
                location: "command.args".to_owned(),
            });
        };
        args[index] = Value::String(format!("--resume={placeholder}"));
        Ok(())
    }

    fn sanitize_paths_and_validate(
        &mut self,
        text: &mut String,
        location: &str,
    ) -> Result<(), SanitizationError> {
        for path in &self.paths {
            for value in &path.values {
                if path_occurrence_escapes_root(text, value) {
                    return Err(SanitizationError::UnrecognizedAbsolutePath {
                        location: location.to_owned(),
                    });
                }
                replace_path_occurrences(text, value, path.placeholder);
            }
        }
        if contains_absolute_path(text) {
            return Err(SanitizationError::UnrecognizedAbsolutePath {
                location: location.to_owned(),
            });
        }
        if contains_secret_value(text) {
            return Err(SanitizationError::SecretLikeValue {
                location: location.to_owned(),
            });
        }
        Ok(())
    }
}

/// `pub(crate)`, not private: `allowlist::named_kind` routes leaf lookup through
/// this same rule (see its doc comment), so Claude's `session_id` and Codex's
/// `sessionId` — if it ever used that spelling — collapse to one entry instead
/// of needing a copy of this function that can drift from this one.
pub(crate) fn normalize_field(field: &str) -> String {
    field
        .chars()
        .filter(|character| character.is_ascii_alphanumeric())
        .flat_map(char::to_lowercase)
        .collect()
}

/// `sanitize_scalar`'s call site only ever passes a `String`/`Number` value —
/// the allowlist walker checks this once per scalar, not once per object key
/// the way the old blocklist did, so `{"apiKey": {"a": "b"}}` no longer trips
/// this check on the `apiKey` object itself. That is deliberate, not a
/// narrowing bug: an object-valued field is walked into regardless (its
/// contents still redact under the same rules, since default-deny already
/// covers any path nobody put on the allowlist), so nothing escapes — this
/// is very likely what made `is_codex_token_usage_object`'s old
/// object-shaped bypass unnecessary. `sanitize_nonsemantic_value`'s call
/// site (the `command`/`platform` metadata scan) still passes object- and
/// array-valued fields, so this function itself stays general.
fn is_secret_field(field: &str, value: &Value) -> bool {
    let normalized = normalize_field(field);
    if is_token_counter_field(&normalized) {
        return !value.is_number();
    }
    normalized == "token"
        || [
            "apitoken",
            "accesstoken",
            "authtoken",
            "bearertoken",
            "idtoken",
            "oauthtoken",
            "personalaccesstoken",
            "refreshtoken",
            "sessiontoken",
            "apikey",
            "clientsecret",
            "privatekey",
            "secretkey",
            "signingkey",
            "credential",
            "credentials",
            "password",
            "authorization",
        ]
        .iter()
        .any(|family| normalized.ends_with(family))
        || normalized == "secret"
}

/// Whether `text` is shaped like a placeholder this sanitizer *generates* —
/// `<V12>`, or a named group with a trailing number (`<SESSION_1>`,
/// `<PROSE_3>`).
///
/// A literal of that shape surviving on an allowlisted path is not safe to
/// keep, because placeholder identity is the archive's join key: equal
/// placeholder means equal original. An allowlisted `"<V1>"` sitting beside a
/// withheld value that was independently assigned `<V1>` reads as a join
/// between two things that were never equal. It cannot be fixed by reserving
/// the name at generation time either — the colliding literal can arrive in a
/// frame *after* the number was handed out — so the capture is rejected and
/// the collision never enters the archive.
///
/// The nine path-root placeholders `Redactor::new` writes (`<HOME>`,
/// `<CODEX_HOME>`, `<TRUSTED_POWERSHELL>`, …) are deliberately **not** this
/// shape: none ends in `_<digits>`. That matters because
/// `sanitize_paths_and_validate` legitimately puts them *inside* allowlisted
/// strings, and the archive re-pass documented in `provider-captures.md`
/// feeds text already carrying them back through. Rejecting those would break
/// a workflow that is working; rejecting a numbered one catches a genuine
/// ambiguity.
fn is_generated_placeholder_shape(text: &str) -> bool {
    let Some(inner) = text
        .strip_prefix('<')
        .and_then(|text| text.strip_suffix('>'))
    else {
        return false;
    };
    let numbered_generic = inner.strip_prefix('V').is_some_and(|digits| {
        !digits.is_empty() && digits.bytes().all(|byte| byte.is_ascii_digit())
    });
    let numbered_named = inner.rsplit_once('_').is_some_and(|(name, number)| {
        !name.is_empty() && !number.is_empty() && number.bytes().all(|byte| byte.is_ascii_digit())
    });
    numbered_generic || numbered_named
}

/// The nine literal path-root placeholders `Redactor::new` writes directly
/// (`<CWD>`, `<REPO>`, `<HOME>`, `<TEMP>`, `<CODEX_HOME>`,
/// `<CLAUDE_CONFIG_DIR>`, `<APPROVAL_TARGET>`, `<TRUSTED_POWERSHELL>`,
/// `<PROGRAM_DIR>`) — never through the numbered `named`/`generic`
/// machinery, so `is_generated_placeholder_shape` alone does not recognize
/// them (see its own doc comment: none ends in `_<digits>`, by design).
///
/// `<PROGRAM_DIR>` is the odd one out in where it comes from: the other eight
/// are `RedactionRoots` fields the recorder wrote, and it is derived at
/// sanitize time from the capture's own `command.program` — see
/// `Redactor::add_uncovered_program_root` for why that is deliberate.
pub const PATH_ROOT_PLACEHOLDERS: [&str; 9] = [
    "<CWD>",
    "<REPO>",
    "<HOME>",
    "<TEMP>",
    "<CODEX_HOME>",
    "<CLAUDE_CONFIG_DIR>",
    "<APPROVAL_TARGET>",
    "<TRUSTED_POWERSHELL>",
    "<PROGRAM_DIR>",
];

/// Whether `text` is shaped like *any* placeholder this sanitizer can
/// produce: a numbered generic/named token (`is_generated_placeholder_shape`)
/// or one of the nine literal path roots above.
///
/// Sound with no declared-per-capture list to check against: `sanitize_scalar`
/// already rejects an allowlisted value that happens to have this shape
/// (`PlaceholderShapedValue`), so nothing kept verbatim in a promoted capture
/// can satisfy this check by coincidence.
pub fn is_placeholder_token(text: &str) -> bool {
    is_generated_placeholder_shape(text) || PATH_ROOT_PLACEHOLDERS.contains(&text)
}

/// A decision this task owns, not Task 1's path review: the tool-name-at-
/// invocation family (`.message.content[].name`, `.event.content_block.name`,
/// `.request.tool_name`, `.last_tool_name`,
/// `.message.content[].content[].tool_name`, `.tool_use_result.matches[]`) is
/// allowlisted, and every sampled value today is a built-in tool name
/// (`Read`, `Bash`, `TaskCreate`). An MCP invocation puts
/// `mcp__<server>__<tool>` in that same field, embedding the server identity
/// `.mcp_servers[].name` and `.tools[]` were both excluded to protect —
/// closing those paths and leaving this one open would undo the fix. A path
/// decision can't express "this field, except when the value looks like
/// this", so the exception lives at the value, checked after the path is
/// already known to be allowed.
///
/// `.request.display_name` was originally in this family and is deliberately
/// no longer allowlisted at all (review finding, 2026-08-15): it exists to
/// hold a *friendly rendering*, not the raw name, so an MCP tool's friendly
/// rendering can plausibly read `create_issue (linear)` — naming
/// the server while never containing the literal `mcp__` prefix this check
/// matches on. `crates/harness/src/claude/wire.rs:694` records the field as
/// present and deliberately undecoded, so by the standing "nothing decodes
/// it" rule it should not have been on the list regardless of the prefix
/// gap.
fn is_mcp_tool_identity(value: &Value) -> bool {
    value.as_str().is_some_and(|text| text.starts_with("mcp__"))
}

/// The type-and-length summary a `NovelPath` reports instead of a value:
/// `"string len 8"` (or `"string len 8-42"` when lengths vary across the
/// distinct values seen), `"number"`, or `"mixed"` when a path's withheld
/// values are not all the same JSON type. String length is counted in
/// `char`s, not bytes, so it reflects what a reader would see rather than a
/// UTF-8 encoding detail.
///
/// `"mixed"` **is** reachable, despite an earlier version of this comment
/// claiming otherwise: `sanitize_value_tree`'s array arm gives every element
/// the same collapsed path (`{path}[]`), so a novel array mixing a string
/// and a number — `["a", 5]` — hands two different `Value` variants to the
/// same path in a single walk.
/// `mixed_type_values_at_one_path_report_as_mixed` proves it directly.
///
/// What genuinely cannot reach here: `Bool`/`Null`/`Array`/`Object`, and an
/// empty slice. `sanitize_value_tree` (line 691) routes only `String`/
/// `Number` into `sanitize_scalar` — everything else falls through its `_ =>
/// Ok(())` arm untouched — and the map-key branch that also feeds
/// `record_novel` always passes a `Value::String`. `values` is never empty
/// either: a path's entry in `self.novel` is created and given its first
/// value in the same call (`record_novel`), so `describe_shape` never sees
/// an entry that exists but holds nothing.
fn describe_shape(values: &[Value]) -> String {
    debug_assert!(
        !values.is_empty(),
        "describe_shape is only ever called on an existing self.novel entry, which record_novel \
         never leaves empty"
    );
    if values.is_empty() {
        // The assertion above is compiled out of a release build, so this is
        // the fallback if the invariant it names ever breaks there — without
        // it, `min_len`/`max_len` stay at their unset `usize::MAX`/`0`
        // starting values and the string branch below would print a
        // nonsensical range like "string len 18446744073709551615-0" instead
        // of failing loudly or degrading safely.
        return "no withheld values".to_owned();
    }
    let mut all_string = true;
    let mut all_number = true;
    let mut min_len = usize::MAX;
    let mut max_len = 0usize;
    for value in values {
        match value {
            Value::String(text) => {
                all_number = false;
                let len = text.chars().count();
                min_len = min_len.min(len);
                max_len = max_len.max(len);
            }
            Value::Number(_) => {
                all_string = false;
            }
            _ => {
                all_string = false;
                all_number = false;
            }
        }
    }
    if all_string {
        if min_len == max_len {
            format!("string len {min_len}")
        } else {
            format!("string len {min_len}-{max_len}")
        }
    } else if all_number {
        "number".to_owned()
    } else {
        "mixed".to_owned()
    }
}

/// Renders the novel-path report for a terminal: a one-line header stating
/// what the list is and that nothing on it is a value, then one aligned row
/// per path, sorted (the order `SanitizationReport::novel_paths` already
/// carries). An empty report still prints a sentence, not silence -- silence
/// after a sanitize run reads as "nothing happened here," not as "everything
/// was already on the allowlist."
///
/// The header promises no *withheld* value or key appears below. It does not
/// promise the paths themselves are contentless: a path names **field names**,
/// which the corpus publishes on purpose (each version's capability sheet
/// under `docs/providers/` is a snapshot of exactly those). A withheld map
/// key is the one thing that could have made
/// that distinction leak, and it is reported at its position (`.modelUsage.{}`)
/// rather than spelled -- see `NovelPath`'s doc comment. Keep the wording
/// honest if this changes: "nothing withheld appears below" is what
/// `record_novel` and `describe_shape` actually enforce, and "nothing
/// identifying appears below" would overstate it.
pub fn render_novel_paths_report(novel_paths: &[NovelPath]) -> String {
    let header = "Novel paths withheld by the allowlist (nothing withheld appears below -- \
                  a withheld map key is counted at its position, e.g. `.modelUsage.{}`, \
                  never spelled):";
    if novel_paths.is_empty() {
        return format!("{header}\n  (none -- every field on the wire was already allowlisted)");
    }
    let path_width = novel_paths
        .iter()
        .map(|entry| entry.path.chars().count())
        .max()
        .unwrap_or(0);
    let count_width = novel_paths
        .iter()
        .map(|entry| count_label(entry.distinct_values).chars().count())
        .max()
        .unwrap_or(0);
    let mut lines = vec![header.to_owned()];
    for entry in novel_paths {
        let count_label = count_label(entry.distinct_values);
        lines.push(format!(
            "  {path:<path_width$}  {count_label:<count_width$}  {shape}",
            path = entry.path,
            shape = entry.shape,
        ));
    }
    lines.join("\n")
}

/// The escaped-key notice that goes under the novel-path report.
///
/// Informational by design. Every path here is *published* — its key is a
/// field name, and field names publish — so this is a "look once at what a
/// new provider calls its fields" list, not a decision queue. It doubles as
/// the place to copy an allowlist spelling from: a line in
/// `allowlist/<provider>.txt` has to equal this string exactly, backslashes
/// included.
pub fn render_escaped_paths_report(escaped_paths: &[String]) -> String {
    let header = "Keys carrying a path delimiter, escaped where they join the path (published as \
                  field names -- copy an allowlist line from here verbatim):";
    if escaped_paths.is_empty() {
        return format!("{header}\n  (none -- no key on the wire carried one)");
    }
    let mut lines = vec![header.to_owned()];
    lines.extend(escaped_paths.iter().map(|path| format!("  {path}")));
    lines.join("\n")
}

fn count_label(distinct_values: usize) -> String {
    if distinct_values == 1 {
        "1 distinct value".to_owned()
    } else {
        format!("{distinct_values} distinct values")
    }
}

