fn contains_secret_value(value: &str) -> bool {
    if contains_ascii_case_insensitive(value, "-----BEGIN ")
        && contains_ascii_case_insensitive(value, " PRIVATE KEY-----")
    {
        return true;
    }
    ["sk-ant-", "sk-proj-", "xoxb-", "ghp_", "github_pat_"]
        .iter()
        .any(|prefix| value.contains(prefix))
        || value
            .match_indices("sk-")
            .any(|(index, _)| index == 0 || !value.as_bytes()[index - 1].is_ascii_alphanumeric())
}

/// Whether `haystack` contains `needle`, comparing ASCII case-insensitively,
/// without allocating an uppercased copy of `haystack` — this runs once per
/// scanned string in the sanitizer's hot loop (~2,900 calls on the largest
/// capture), and `to_ascii_uppercase` was paying for a full string clone on
/// every call just to test for one fixed-case literal.
fn contains_ascii_case_insensitive(haystack: &str, needle: &str) -> bool {
    let haystack = haystack.as_bytes();
    let needle = needle.as_bytes();
    needle.len() <= haystack.len()
        && haystack
            .windows(needle.len())
            .any(|window| window.eq_ignore_ascii_case(needle))
}

fn replace_path_occurrences(text: &mut String, path: &str, placeholder: &str) -> u64 {
    let mut count = 0;
    let mut cursor = 0;
    while let Some(relative) = text[cursor..].find(path) {
        let start = cursor + relative;
        let end = start + path.len();
        let ends_at_path_boundary = end == text.len()
            || text[end..]
                .chars()
                .next()
                .is_some_and(|character| matches!(character, '/' | '\\' | '"' | '\''));
        if ends_at_path_boundary {
            text.replace_range(start..end, placeholder);
            cursor = start + placeholder.len();
            count += 1;
        } else {
            cursor = end;
        }
    }
    count
}

fn path_occurrence_escapes_root(text: &str, root: &str) -> bool {
    let mut cursor = 0;
    while let Some(relative) = text[cursor..].find(root) {
        let end = cursor + relative + root.len();
        let tail = &text[end..];
        if tail.starts_with(['/', '\\']) {
            let path_tail = tail
                .split(|character: char| {
                    character.is_whitespace() || matches!(character, '"' | '\'' | '<' | '>' | '|')
                })
                .next()
                .unwrap_or(tail);
            let mut depth = 0usize;
            for component in path_tail.split(['/', '\\']).filter(|part| !part.is_empty()) {
                match component {
                    "." => {}
                    ".." if depth == 0 => return true,
                    ".." => depth -= 1,
                    _ => depth += 1,
                }
            }
        }
        cursor = end;
    }
    false
}

fn contains_absolute_path(value: &str) -> bool {
    let bytes = value.as_bytes();
    for index in 0..bytes.len() {
        if index + 2 < bytes.len()
            && bytes[index].is_ascii_alphabetic()
            && bytes[index + 1] == b':'
            && matches!(bytes[index + 2], b'/' | b'\\')
            && (index == 0 || !bytes[index - 1].is_ascii_alphanumeric())
        {
            return true;
        }
        if index + 1 < bytes.len() && bytes[index] == b'\\' && bytes[index + 1] == b'\\' {
            return true;
        }
        if index + 1 < bytes.len()
            && bytes[index] == b'/'
            && bytes[index + 1] == b'/'
            && (index == 0 || !matches!(bytes[index - 1], b':' | b'/'))
        {
            return true;
        }
        if bytes[index] == b'/'
            && bytes.get(index + 1).is_some_and(|next| {
                !next.is_ascii_whitespace() && !matches!(*next, b'/' | b'>' | b'}' | b']')
            })
            && (index == 0
                || (!bytes[index - 1].is_ascii_alphanumeric()
                    && !matches!(bytes[index - 1], b':' | b'/' | b'>')))
        {
            return true;
        }
    }
    false
}

fn is_drive_absolute(value: &str) -> bool {
    let bytes = value.as_bytes();
    bytes.len() >= 3
        && bytes[0].is_ascii_alphabetic()
        && bytes[1] == b':'
        && matches!(bytes[2], b'/' | b'\\')
}

fn is_staging_output(output: &Path) -> bool {
    if output
        .components()
        .any(|component| matches!(component, std::path::Component::ParentDir))
    {
        return false;
    }
    let components: Vec<_> = output
        .components()
        .filter_map(|component| component.as_os_str().to_str())
        .collect();
    components.windows(2).any(|pair| {
        pair[0] == ".comet-provider-captures" && pair[1].eq_ignore_ascii_case("staging")
    })
}

